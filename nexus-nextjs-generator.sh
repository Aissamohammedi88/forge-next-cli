#!/usr/bin/env bash
# ==============================================================================
# NEXUS NEXT.JS GENERATOR v1.0.0 — ÉDITION BASH LINUX
# Générateur de projet Next.js interactif avec API Routes.
# Lancement local automatique.
#
# Port bash 1:1 du générateur Python original — spécification DGK.
# Prérequis : bash >= 4, Node.js >= 18.17, npm, Linux (xdg-open optionnel)
# ==============================================================================

set -u

# ==============================================================================
# CONFIGURATION & COULEURS TERMINAL
# ==============================================================================
GREEN=$'\033[92m'
CYAN=$'\033[96m'
YELLOW=$'\033[93m'
RED=$'\033[91m'
RESET=$'\033[0m'

log_info() { printf '%s[INFO]%s %s\n' "$CYAN" "$RESET" "$*"; }
log_ok()   { printf '%s[OK]%s %s\n'   "$GREEN" "$RESET" "$*"; }
log_warn() { printf '%s[WARN]%s %s\n' "$YELLOW" "$RESET" "$*"; }
log_err()  { printf '%s[ERR]%s %s\n'  "$RED" "$RESET" "$*"; }

on_interrupt_top() {
    printf '\n'
    log_warn "Annulé par l'utilisateur."
    exit 130
}

on_interrupt_server() {
    printf '\n'
    log_warn "Serveur arrêté proprement."
    exit 130
}

# ==============================================================================
# GÉNÉRATION DES FICHIERS DU PROJET
# ==============================================================================

create_project_structure() {
    local base_path="$1"
    log_info "Création du projet dans $base_path"

    # Création des dossiers
    mkdir -p "$base_path/src/app" \
             "$base_path/src/app/api/hello" \
             "$base_path/public"

    # --- package.json ---
    cat > "$base_path/package.json" <<'NEXUS_EOF'
{
  "name": "nexus-app",
  "version": "1.0.0",
  "private": true,
  "scripts": {
    "dev": "next dev",
    "build": "next build",
    "start": "next start",
    "lint": "next lint"
  },
  "dependencies": {
    "next": "14.2.3",
    "react": "^18",
    "react-dom": "^18"
  },
  "devDependencies": {
    "typescript": "^5",
    "@types/node": "^20",
    "@types/react": "^18",
    "@types/react-dom": "^18",
    "tailwindcss": "^3.4.1",
    "postcss": "^8",
    "autoprefixer": "^10.0.1"
  }
}
NEXUS_EOF
    log_ok "Fichier créé : package.json"

    # --- next.config.mjs ---
    cat > "$base_path/next.config.mjs" <<'NEXUS_EOF'
/** @type {import('next').NextConfig} */
const nextConfig = {
  reactStrictMode: true,
};

export default nextConfig;
NEXUS_EOF
    log_ok "Fichier créé : next.config.mjs"

    # --- tailwind.config.ts ---
    cat > "$base_path/tailwind.config.ts" <<'NEXUS_EOF'
import type { Config } from "tailwindcss";

const config: Config = {
  content: [
    "./src/pages/**/*.{js,ts,jsx,tsx,mdx}",
    "./src/components/**/*.{js,ts,jsx,tsx,mdx}",
    "./src/app/**/*.{js,ts,jsx,tsx,mdx}",
  ],
  theme: {
    extend: {
      colors: {
        nexus: {
          bg: "#050810",
          panel: "#0a1424",
          border: "#1a3a5a",
          cyan: "#00d4ff",
          pink: "#ff0080",
        }
      }
    },
  },
  plugins: [],
};
export default config;
NEXUS_EOF
    log_ok "Fichier créé : tailwind.config.ts"

    # --- postcss.config.mjs ---
    cat > "$base_path/postcss.config.mjs" <<'NEXUS_EOF'
/** @type {import('postcss-load-config').Config} */
const config = {
  plugins: {
    tailwindcss: {},
  },
};

export default config;
NEXUS_EOF
    log_ok "Fichier créé : postcss.config.mjs"

    # --- src/app/layout.tsx ---
    cat > "$base_path/src/app/layout.tsx" <<'NEXUS_EOF'
import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Nexus App",
  description: "Generated by Nexus Generator",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="fr">
      <body className={inter.className}>{children}</body>
    </html>
  );
}
NEXUS_EOF
    log_ok "Fichier créé : src/app/layout.tsx"

    # --- src/app/globals.css ---
    cat > "$base_path/src/app/globals.css" <<'NEXUS_EOF'
@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
  --foreground-rgb: 255, 255, 255;
  --background-start-rgb: 5, 8, 16;
  --background-end-rgb: 5, 8, 16;
}

body {
  color: rgb(var(--foreground-rgb));
  background: linear-gradient(
    to bottom,
    transparent,
    rgb(var(--background-end-rgb))
  )
  rgb(var(--background-start-rgb));
}
NEXUS_EOF
    log_ok "Fichier créé : src/app/globals.css"

    # --- src/app/page.tsx ---
    cat > "$base_path/src/app/page.tsx" <<'NEXUS_EOF'
'use client';

import { useState, useEffect } from 'react';

export default function Home() {
  const [data, setData] = useState<any>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch('/api/hello')
      .then(res => res.json())
      .then(d => {
        setData(d);
        setLoading(false);
      });
  }, []);

  return (
    <main className="flex min-h-screen flex-col items-center justify-center p-24">
      <div className="z-10 max-w-5xl w-full items-center justify-between font-mono text-sm">
        <h1 className="text-5xl font-bold text-nexus-cyan mb-8 text-center">
          ⚡ NEXUS APP
        </h1>

        <div className="bg-nexus-panel border border-nexus-border p-8 rounded-xl shadow-2xl">
          <h2 className="text-2xl text-white mb-4">Statut de l'API</h2>

          {loading ? (
            <p className="text-nexus-cyan animate-pulse">Connexion à l'API locale...</p>
          ) : (
            <div className="space-y-4">
              <div className="bg-black p-4 rounded border border-nexus-border">
                <pre className="text-green-400">{JSON.stringify(data, null, 2)}</pre>
              </div>
              <p className="text-gray-400 text-sm">
                Cette donnée provient de la route API locale <code>/api/hello</code>
              </p>
            </div>
          )}
        </div>
      </div>
    </main>
  );
}
NEXUS_EOF
    log_ok "Fichier créé : src/app/page.tsx"

    # --- src/app/api/hello/route.ts ---
    cat > "$base_path/src/app/api/hello/route.ts" <<'NEXUS_EOF'
import { NextResponse } from 'next/server';

export async function GET() {
  return NextResponse.json({
    message: "Bienvenue sur l'API Nexus",
    status: "online",
    timestamp: new Date().toISOString(),
    version: "1.0.0"
  });
}

export async function POST(request: Request) {
  try {
    const body = await request.json();
    return NextResponse.json({
      received: body,
      status: "success",
      processed_at: new Date().toISOString()
    });
  } catch (error) {
    return NextResponse.json(
      { error: "Invalid JSON payload" },
      { status: 400 }
    );
  }
}
NEXUS_EOF
    log_ok "Fichier créé : src/app/api/hello/route.ts"
}

# ==============================================================================
# LOGIQUE DU GÉNÉRATEUR
# ==============================================================================

install_dependencies() {
    local base_path="$1"

    if ! command -v npm >/dev/null 2>&1; then
        log_err "NPM n'est pas installé sur votre système."
        log_info "Veuillez installer Node.js : https://nodejs.org/"
        exit 1
    fi

    log_info "Installation des dépendances (npm install)..."
    log_warn "Cela peut prendre 1 à 2 minutes..."

    if (cd "$base_path" && npm install); then
        log_ok "Dépendances installées avec succès."
    else
        log_err "Erreur lors de l'installation :"
        exit 1
    fi
}

start_server() {
    local base_path="$1"
    log_info "Lancement du serveur Next.js (npm run dev)..."

    # Ouverture du navigateur après 3 secondes
    (
        sleep 3
        log_ok "Ouverture du navigateur sur http://localhost:3000"
        if command -v xdg-open >/dev/null 2>&1; then
            xdg-open "http://localhost:3000" >/dev/null 2>&1
        fi
    ) &

    trap on_interrupt_server INT
    cd "$base_path" || exit 1
    npm run dev
}

main() {
    cat <<NEXUS_BANNER

${CYAN}================================================================${RESET}
⚡ NEXUS NEXT.JS GENERATOR v1.0.0
Générateur d'application avec API Routes.
${CYAN}================================================================${RESET}

NEXUS_BANNER

    # 1. Demande du nom du projet
    read -r -p "Nom du projet (défaut: nexus-app) : " project_name
    if [ -z "$project_name" ]; then
        project_name="nexus-app"
    fi

    # Nettoyage du nom (remplace les espaces par des tirets)
    project_name="${project_name// /-}"
    project_name="${project_name,,}"

    local base_path="$(pwd)/$project_name"

    if [ -e "$base_path" ]; then
        log_err "Le dossier '$project_name' existe déjà."
        exit 1
    fi

    # 2. Génération des fichiers
    create_project_structure "$base_path"

    # 3. Installation
    install_dependencies "$base_path"

    # 4. Lancement
    printf '\n'
    log_ok "✨ Projet généré avec succès !"
    log_info "Route API disponible : http://localhost:3000/api/hello"
    printf '\n'

    start_server "$base_path"
}

if [ "${BASH_VERSINFO[0]:-0}" -lt 4 ]; then
    log_err "Bash >= 4 requis (version actuelle : ${BASH_VERSION:-inconnue})."
    exit 1
fi

trap on_interrupt_top INT
main "$@"
